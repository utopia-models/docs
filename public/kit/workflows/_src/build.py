#!/usr/bin/env python3
"""Generate the ten tier templates from five YAML files and seven shared blocks.

    python3 build.py            write tiers/
    python3 build.py --check    exit 1 if anything is stale

WHY GENERATE RATHER THAN AUTHOR TEN FILES BY HAND:
An HTTP fetch of a file containing an include directive delivers the literal directive to the model —
the consumer cannot resolve it. So the served file must be FLAT either way, and the only question is
whether flatness comes from authoring or from generating. Ten hand-authored files drift the first
time someone edits one and forgets the others; generation makes that impossible and the diff shows it.

WHY NO CONDITIONALS IN HERE:
If this file grows `if tier == 3`, the data model is wrong and the fix is in the YAML. That rule is
what keeps this a renderer rather than a second place where behaviour lives.
"""
import sys, pathlib, re

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "tiers"
TIERS = ["1-bare", "2-configured", "3-organized", "4-dispatch", "4-context"]


def block(name: str, root: pathlib.Path = HERE) -> str:
    return (root / "blocks" / f"{name}.md").read_text().strip()


def load(slug: str, root: pathlib.Path = HERE) -> dict:
    """A deliberately small YAML subset: scalar, folded scalar, list of scalars, list of name/why,
    and one nested q/a map. No PyYAML — this runs in CI on a box that may not have it, and a build
    step needing a pip install is a build step that stops being run.

    Written as an explicit state machine rather than a clever one-pass loop: the first version
    guessed the container type from indentation and put a string key into a list.

    `root` is the only parameter a second module needs: a pattern module under `kit/patterns/<id>/`
    imports this loader and these blocks and passes its own `_src/`, so the parser and the
    module-agnostic blocks exist once (knowledge#7761).
    """
    lines = (root / "tiers" / f"{slug}.yaml").read_text().split("\n")
    d: dict = {}
    key = None          # the top-level key currently being filled
    mode = None         # "scalar" | "list" | "objlist" | "map"
    for raw in lines:
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue

        # a top-level key starts at column 0
        if not raw.startswith(" "):
            key, _, val = raw.partition(":")
            key, val = key.strip(), val.strip()
            if val in (">-", "|", ""):
                d[key], mode = None, None   # decided by the first child line
            else:
                d[key], mode = val, "scalar"
            continue

        body = raw.strip()

        # "  - name: x" opens a list of objects
        if body.startswith("- name:"):
            if mode != "objlist":
                d[key], mode = [], "objlist"
            d[key].append({"name": body.split(":", 1)[1].strip()})
            continue
        if mode == "objlist" and body.startswith("why:"):
            d[key][-1]["why"] = body.split(":", 1)[1].strip()
            continue

        # "  - text" is a plain list item
        if body.startswith("- "):
            if mode != "list":
                d[key], mode = [], "list"
            d[key].append(body[2:].strip())
            continue

        # "  q:" / "  a:" opens a nested map
        m = re.match(r"^([a-z_]+):\s*(.*)$", body)
        if m and mode in (None, "map"):
            if mode != "map":
                d[key], mode = {}, "map"
            sub, val = m.group(1), m.group(2).strip()
            d[key][sub] = "" if val in (">-", "|", "") else val
            d.setdefault("_sub", {})[key] = sub
            continue

        # anything else is a continuation of a folded scalar
        if mode == "map":
            sub = d["_sub"][key]
            d[key][sub] = (d[key][sub] + " " + body).strip()
        else:
            mode = "scalar"
            d[key] = ((d[key] or "") + " " + body).strip()
    d.pop("_sub", None)
    return d


def interview(t: dict) -> str:
    qs = "\n\n".join(f"{i}. {q}" for i, q in enumerate(t["questions"], 1))
    gates = "\n".join(f"- **{g['name']}** — {g['why']}" for g in t["gates"])
    return f"""<!-- Generated by _src/build.py from {t['slug']}.yaml. DO NOT EDIT. -->

# Interview — {t['name']}

**Everyone whose setup looks like this should read this file.** {t['situation']}

{block('preamble')}

---

{block('checklist')}

---

{block('output-folder')}

---

{block('measured-vs-inferred')}

---

{block('asking-rules')}

---

## The questions

These are the ones a command cannot answer. Ask them one at a time, in this order, and stop early if
you can already write the files.

{qs}

**Then one more, always, and it is the highest-yield question in the set:**

What should I have asked you and did not?

---

## The objection you should expect

> **{t['objection']['q']}**

{t['objection']['a']}

Answer it before they raise it, not after.

---

## What this tier is missing, and what closes it

{gates}

Name these in `TIER.md`. Do not present them as failure — a setup that is deliberately here is
correctly classified, not behind.

---

{block('outputs')}

---

{block('handoff')}
"""


def execution(t: dict) -> str:
    gates = "\n".join(f"- **{g['name']}** — {g['why']}" for g in t["gates"])
    return f"""<!-- Generated by _src/build.py from {t['slug']}.yaml. DO NOT EDIT. -->

# Execution — {t['name']}

**Everyone whose setup looks like this should read this file.** {t['situation']}

You are building now. Read the four files the interview wrote before you touch anything.

---

## Read first

    <folder>/CONTEXT-MAP.md      what loads, what fires, what costs
    <folder>/INTERVIEW.md        what they said, marked measured or stated
    <folder>/TIER.md             the tier and the three dimension scores
    <folder>/DECISIONS.md        what has already been settled

If any is missing, stop and say which. Building from a partial record is how you produce something
that contradicts a decision already made.

---

## The gate — the thing that makes this durable

**The gate is the mechanism by which the school reaches this person's agent WITHOUT them remembering
it exists.** A module they have to remember is a module they will not use.

Present your options ranked, with **exactly one marked RECOMMENDED** and one line of why each. Then
build the one they choose.

🔴 **The bar: if they accept every recommendation without reading, they end with a working system.**
That is what separates a recommendation from a menu with a default.

For this tier, rank the options against what `CONTEXT-MAP.md` shows they actually have. Do not offer a
mechanism their Claude Code setup does not support, and say so if the obvious one is unavailable here.

---

## What to build

Every tier gets at least these three, and they are the minimum rather than the target:

**A way to run a module.** Given a module URL, fetch it, extract its Claude Code prompt, prepare
whatever it needs, and hand it over ready to run.

**A record of what has been run.** One row per module: which, when, what artifact it produced and
where that artifact lives, and **what changed as a result**.

🔴 **The last column is the one that matters. A row marked done with nothing in the what-changed
column is a module that was not completed** — and the record should make that visible rather than let
a tick hide it.

**A way to learn a new module exists.** The school adds modules. Something must re-check. Do not build
a background process for this — a check that runs when they next work is enough, and a daemon is a
thing that breaks silently while continuing to look healthy.

---

## What closes this tier's gaps

{gates}

Build toward these where the interview showed appetite. Where it did not, say so and leave them —
building against a gap the person does not have is how a durable system becomes an abandoned one.

---

## Prove it fires — both tests, always

Do not report that the gate works. Show it:

    say a sentence that SHOULD trigger it     →  it fired
    say a sentence that should NOT trigger it →  it stayed quiet

🔴 **A gate that fires on everything is as broken as one that fires on nothing, and only the negative
test catches it.** If either fails, fix the description and run both again.

Then verify the rest against reality: the tracker's paths resolve to files that exist, and the
always-on cost in `CONTEXT-MAP.md` matches what Claude Code actually loads now that you have added to
it.

---

## Finish

Every file created, its path, and the two test results with their real output.

Append to `DECISIONS.md`: what you recommended, what they chose, and what you did not build.

Then stop.
"""


def main() -> int:
    check = "--check" in sys.argv
    OUT.mkdir(exist_ok=True)
    stale, total_shared = [], 0
    for slug in TIERS:
        t = load(slug)
        t["slug"] = slug
        for kind, fn in (("interview", interview), ("execution", execution)):
            path = OUT / f"{slug}-{kind}.md"
            new = fn(t)
            if check:
                if not path.exists() or path.read_text() != new:
                    stale.append(path.name)
            else:
                path.write_text(new)
    if check:
        if stale:
            print("STALE (run build.py):", " ".join(stale))
            return 1
        print(f"up to date — {len(TIERS)*2} files")
        return 0
    sizes = [(p.name, p.stat().st_size) for p in sorted(OUT.glob("*.md"))]
    for n, s in sizes:
        print(f"  {n:34} {s:6d} B")
    # The shared fraction, printed rather than assumed: if the deltas exceed ~50% the shared layer was
    # never worth extracting, and if the files are ~90% identical a two-fetch design would pay.
    shared = sum(len(block(b)) for b in
                 ["preamble", "checklist", "output-folder", "measured-vs-inferred",
                  "asking-rules", "outputs", "handoff"])
    avg = sum(s for _, s in sizes if "interview" in _) / max(1, len([1 for n, _ in sizes if "interview" in n]))
    print(f"\n  shared blocks: {shared} B · avg interview: {avg:.0f} B · shared fraction ~{shared/avg:.0%}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
